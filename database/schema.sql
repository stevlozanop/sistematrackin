-- Empresas: la transportista dueña del sistema (Consorcio Leyva) y consorcios cliente (Honda)
CREATE TABLE IF NOT EXISTS companies (
  id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name         citext NOT NULL UNIQUE,
  kind         citext NOT NULL DEFAULT 'transport' CHECK (kind IN ('transport', 'client')),
  code         citext UNIQUE,     -- código por tipo según su orden: empresas EMP-01, EMP-02… · consorcios CON-01…
  slug         citext UNIQUE,     -- consorcio: su entrada propia /<slug> (empleados) y /<slug>/clientes
  parent_id    integer REFERENCES companies(id) ON DELETE SET NULL, -- consorcio cliente: la transportista que lo creó (Honda -> Leyva)
  owner_id     integer,           -- cuenta principal de la empresa (users.id; la FK se agrega más abajo)
  color        varchar(7),        -- color principal de su tema (#078a04 Leyva, #cc0000 Honda)
  ruc          citext,
  members      citext,            -- transportistas del grupo tal como aparecen en units.carrier, separados por coma
  address      citext,
  phone        citext,
  email        citext,
  website      citext,
  notes        citext,
  created_at   timestamp(0) NOT NULL DEFAULT LOCALTIMESTAMP(0),
  logo         bytea,             -- foto de perfil / logo (imagen pequeña, 256 px)
  logo_type    varchar(20),       -- image/webp, image/png o image/jpeg
  logo_updated timestamp(0)       -- para refrescar la imagen en los navegadores al cambiarla
);

