-- updated_at cambia solo si algún dato cambió (como ON UPDATE CURRENT_TIMESTAMP de MySQL)
CREATE OR REPLACE FUNCTION units_touch() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.updated_at IS NOT DISTINCT FROM OLD.updated_at AND ROW(NEW.*) IS DISTINCT FROM ROW(OLD.*) THEN
    NEW.updated_at := LOCALTIMESTAMP(0);
  END IF;
  RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS trg_units_touch ON units;
CREATE TRIGGER trg_units_touch BEFORE UPDATE ON units FOR EACH ROW EXECUTE FUNCTION units_touch();

